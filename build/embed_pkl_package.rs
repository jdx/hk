use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};

/// Modules that must be present to stand in for the released archive. A partial
/// package would poison the cache instead of falling back to the network.
const REQUIRED_MODULES: &[&str] = &["Builtins.pkl", "Config.pkl", "Types.pkl", "UserConfig.pkl"];

/// Files `pkl project package` keeps out of the published archive.
const EXCLUDED: &[&str] = &["PklProject", "PklProject.deps.json", ".gitignore"];

/// Stage a zip of the pkl sources mirroring the released `hk@VERSION.zip`.
///
/// Writes an empty file when the sources have not been generated by `pkl:gen`;
/// hk then fetches the package normally. `HK_REQUIRE_EMBEDDED_PKL` turns that
/// fallback into a build failure, which is what release builds want.
pub fn generate(out_dir: &Path) -> Result<(), std::io::Error> {
    let pkl_dir = Path::new("pkl");
    let dest_path = out_dir.join("hk_pkl_package.zip");

    let entries = collect_entries(pkl_dir)?;
    let missing: Vec<&str> = REQUIRED_MODULES
        .iter()
        .filter(|module| !entries.iter().any(|(name, _)| name == *module))
        .copied()
        .collect();
    if !missing.is_empty() {
        if std::env::var_os("HK_REQUIRE_EMBEDDED_PKL").is_some_and(|v| v != "0") {
            return Err(std::io::Error::other(format!(
                "HK_REQUIRE_EMBEDDED_PKL is set but these pkl modules are missing: {}. \
                 Run `mise run pkl:gen` before building.",
                missing.join(", ")
            )));
        }
        fs::write(&dest_path, b"")?;
        return Ok(());
    }

    let mut zip = zip::ZipWriter::new(std::io::Cursor::new(Vec::new()));
    // A fixed timestamp keeps the archive identical across rebuilds.
    let options = zip::write::SimpleFileOptions::default()
        .compression_method(zip::CompressionMethod::Deflated)
        .last_modified_time(zip::DateTime::default());
    for (name, path) in &entries {
        zip.start_file(name, options)
            .map_err(std::io::Error::other)?;
        zip.write_all(&fs::read(path)?)?;
    }
    let archive = zip.finish().map_err(std::io::Error::other)?.into_inner();
    fs::write(&dest_path, archive)?;
    Ok(())
}

/// Collect the archive entries as (name within the archive, source path),
/// sorted so the archive order does not depend on directory iteration order.
fn collect_entries(pkl_dir: &Path) -> Result<Vec<(String, PathBuf)>, std::io::Error> {
    let mut entries = Vec::new();
    collect_dir(pkl_dir, "", &mut entries)?;
    entries.sort();
    Ok(entries)
}

/// Add the regular files under `dir` to `entries`, recursing into subdirectories.
fn collect_dir(
    dir: &Path,
    prefix: &str,
    entries: &mut Vec<(String, PathBuf)>,
) -> Result<(), std::io::Error> {
    // read_dir follows links, so check the root the way entries are checked below.
    match fs::symlink_metadata(dir) {
        Ok(metadata) if metadata.file_type().is_symlink() => {
            return Err(std::io::Error::other(format!(
                "refusing to embed symbolic link: {}",
                dir.display()
            )));
        }
        Ok(_) => {}
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(()),
        Err(error) => return Err(error),
    }
    for entry in fs::read_dir(dir)? {
        let entry = entry?;
        let file_name = entry.file_name();
        let Some(file_name) = file_name.to_str() else {
            return Err(std::io::Error::other(format!(
                "pkl source name is not valid UTF-8: {}",
                entry.path().display()
            )));
        };
        // Archive paths always use forward slashes, on every platform.
        let name = format!("{prefix}{file_name}");
        let file_type = entry.file_type()?;
        if file_type.is_dir() {
            collect_dir(&entry.path(), &format!("{name}/"), entries)?;
        } else if file_type.is_symlink() {
            // Reading through a link would embed whatever it points at on this machine.
            return Err(std::io::Error::other(format!(
                "refusing to embed symbolic link: {}",
                entry.path().display()
            )));
        } else if file_type.is_file() && !EXCLUDED.contains(&name.as_str()) {
            entries.push((name, entry.path()));
        }
    }
    Ok(())
}
