// The generated pirate CLI reference (pirate-cli.mjs): how an English page
// becomes its pirate page, and that docs/pirate/cli is what it generates.

import assert from "node:assert/strict";
import { existsSync, globSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { after, test } from "node:test";
import { cliPages, generate, hasProse, pirateCliPage, readWords, slugify, translatePage } from "./pirate-cli.mjs";
import { DOCS } from "./pirate-pages.mjs";

const WORDS = {
  labels: { "- **Usage:** ": "- **How to hail it:** " },
  lines: {
    'description: "Check files."': 'description: "Inspect the cargo."',
    "## Flags": "## Flags to fly",
    "## Learn more": "## Further charts",
    "Check files": "Inspect the cargo",
    "- **`-a --all`** — Select all files": "- **`-a --all`** — Take the whole o' the cargo",
    "Set up a project": "Rig a ship",
    Task: "The task",
    Command: "The call",
    "[hk init](/cli/init)": "[hk init](/cli/init)",
    "hk check --all": "arr, this must never reach a code block",
  },
  pages: { "fix.md": { "Check files": "Mend the canvas" } },
};

const PAGE = `---
title: "hk check"
description: "Check files."
---

<!-- @generated by usage-cli from usage spec -->

# \`hk check\`

- **Usage:** \`hk check [FLAGS]\`

Check files

## Flags

- **\`-a --all\`** — Select all files
- **\`-h --help\`** — Print help

| Task | Command |
| --- | --- |
| Set up a project | [hk init](/cli/init) |

\`\`\`sh
hk check --all
\`\`\`

## Learn more
`;

test("VitePress's slugs, so pirate headings keep the English anchors", () => {
  assert.equal(slugify("Arguments"), "arguments");
  assert.equal(slugify("Learn more"), "learn-more");
  assert.equal(slugify("Global Flags"), "global-flags");
  assert.equal(slugify("hk.pkl files"), "hk-pkl-files");
  assert.equal(slugify("1st steps"), "_1st-steps");
  assert.equal(slugify("Café naïve?"), "cafe-naive");
  // VitePress keeps a dash it does not know, and so does this.
  assert.equal(slugify("A — B"), "a-—-b");
});

test("an English page becomes the same page in the crew's words", () => {
  const { front, body, untranslated } = translatePage(PAGE, "check.md", WORDS);
  assert.deepEqual(front, ['title: "hk check"', 'description: "Inspect the cargo."']);
  assert.equal(
    body,
    `
<!-- @generated by docs/.vitepress/pirate-cli.mjs from docs/cli/check.md and docs/pirate/cli.json; edit those, not this page. -->

# \`hk check\`

- **How to hail it:** \`hk check [FLAGS]\`

Inspect the cargo

## Flags to fly {#flags}

- **\`-a --all\`** — Take the whole o' the cargo
- **\`-h --help\`** — Print help

| The task   | The call             |
| ---------- | -------------------- |
| Rig a ship | [hk init](/cli/init) |

\`\`\`sh
hk check --all
\`\`\`

## Further charts {#learn-more}
`,
  );
  assert.deepEqual(untranslated, ["- **`-h --help`** — Print help"], "a line with no words stays in English, and is reported");
});

test("a page's own words beat the shared ones", () => {
  assert.match(translatePage(PAGE, "fix.md", WORDS).body, /^Mend the canvas$/m);
  assert.match(translatePage(PAGE, "check.md", WORDS).body, /^Inspect the cargo$/m);
});

test("headings keep their anchors: custom ones, repeated ones, and untranslated ones", () => {
  const { body } = translatePage("## Flags\n\n## Flags\n\n## Setup {#set-up}\n\n## Other\n", "x.md", WORDS);
  assert.equal(body, "## Flags to fly {#flags}\n\n## Flags to fly {#flags-1}\n\n## Setup {#set-up}\n\n## Other\n");
});

test("a translated h1 keeps the English anchor too", () => {
  const { body } = translatePage("# CLI reference\n\n## Flags\n", "index.md", { lines: { "# CLI reference": "# The bosun's calls", "## Flags": "## Flags to fly" } });
  assert.equal(body, "# The bosun's calls {#cli-reference}\n\n## Flags to fly {#flags}\n");
  assert.equal(translatePage("# `hk check`\n", "check.md", {}).body, "# `hk check`\n", "an untranslated h1 is left as it is");
});

test("heading words may bring the English anchor, and no other", () => {
  const withAnchor = { lines: { "## Flags": "## Flags to fly {#flags}" } };
  assert.equal(translatePage("## Flags\n\n## Flags\n", "x.md", withAnchor).body, "## Flags to fly {#flags}\n\n## Flags to fly {#flags-1}\n");
  assert.throws(() => translatePage("## Flags\n", "x.md", { lines: { "## Flags": "## Flags to fly {#flying}" } }), /needs \{#flags\}/);
});

test("slugs read code and words as VitePress does", () => {
  const words = { lines: { "## `HK_MISE` and `HK_FILE`": "## Orders", "## check_diff output": "## The patch", "## A *bold* <em>move</em>": "## Arr" } };
  const { body } = translatePage("## `HK_MISE` and `HK_FILE`\n\n## check_diff output\n\n## A *bold* <em>move</em>\n", "x.md", words);
  assert.equal(body, "## Orders {#hk-mise-and-hk-file}\n\n## The patch {#check-diff-output}\n\n## Arr {#a-bold-move}\n");
});

test("tables keep escaped pipes in their cells, and their columns' alignment", () => {
  const english = "| Left | Right | Mid |\n| :--- | ---: | :-: |\n| Pick a \\| b | `a\\|b` | x |\n";
  const words = { lines: { Left: "Port", Right: "Starboard", Mid: "Midships", "Pick a \\| b": "Choose a \\| b" } };
  assert.equal(
    translatePage(english, "x.md", words).body,
    "| Port          | Starboard | Midships |\n| :------------ | --------: | :------: |\n| Choose a \\| b |    `a\\|b` |    x     |\n",
  );
});

test("only the crew's own words count: nothing inherited from JavaScript objects", () => {
  const { body, untranslated } = translatePage("| constructor |\n| --- |\n| toString |\n\nvalueOf\n", "constructor", {});
  assert.equal(body, "| constructor |\n| ----------- |\n| toString    |\n\nvalueOf\n");
  assert.deepEqual(untranslated, ["constructor", "toString", "valueOf"]);
});

test("comments are copied, and includes still reach their files from under docs/pirate", () => {
  // From docs/cli/util/x.md: docs/gen is outside docs/cli, and ./fix.md is a CLI page the pirate pages mirror.
  const english = "<!--@include: ../../gen/builtins.md-->\n<!--@include: ./fix.md#flags-->\n<!--@include: @/gen/x.md-->\n<!--\na note\nfor maintainers\n-->\n";
  assert.equal(
    translatePage(english, "util/x.md", {}).body,
    "<!--@include: ../../../gen/builtins.md-->\n<!--@include: ./fix.md#flags-->\n<!--@include: @/gen/x.md-->\n<!--\na note\nfor maintainers\n-->\n",
  );
  assert.deepEqual(translatePage(english, "util/x.md", {}).untranslated, [], "a comment's words are not the page's");
});

test("front matter the crew has no words for is listed, not counted on the page", () => {
  const { untranslated, frontUntranslated } = translatePage('---\ndescription: "Brand new."\n---\n\nBrand new.\n', "x.md", {});
  assert.deepEqual(untranslated, ["Brand new."]);
  assert.deepEqual(frontUntranslated, ['description: "Brand new."']);
});

test("only prose counts as untranslated", () => {
  assert.equal(hasProse("- [`hk util check-symlinks`](/cli/util/check-symlinks.md)"), false);
  assert.equal(hasProse("# `hk check`"), false);
  assert.equal(hasProse("- **`-h --help`** — Print help"), true);
  const { untranslated } = translatePage('---\ntitle: "hk run"\n---\n\n# `hk run`\n', "run.md", {});
  assert.deepEqual(untranslated, [], "a command's title is its name, not words to translate");
});

test("generating writes a page per English page and removes the rest", () => {
  const docs = mkdtempSync(join(tmpdir(), "pirate-cli-"));
  after(() => rmSync(docs, { recursive: true, force: true }));
  mkdirSync(join(docs, "cli/sub"), { recursive: true });
  mkdirSync(join(docs, "pirate/cli"), { recursive: true });
  writeFileSync(join(docs, "cli/check.md"), PAGE);
  writeFileSync(join(docs, "cli/sub/new.md"), "# `hk sub new`\n\nA new command\n");
  writeFileSync(join(docs, "pirate/cli/gone.md"), "an old page for a removed command\n");
  const { pages, missing } = generate(WORDS, docs);
  assert.deepEqual(pages, ["check.md", "sub/new.md"]);
  assert.equal(existsSync(join(docs, "pirate/cli/gone.md")), false);
  const fresh = readFileSync(join(docs, "pirate/cli/sub/new.md"), "utf8");
  assert.match(fresh, /^---\nsourceHash: [0-9a-f]{12}\npirateUntranslated: 1\n---\n/, "a page with English lines says how many");
  assert.deepEqual(missing, [
    { page: "check.md", line: "- **`-h --help`** — Print help" },
    { page: "sub/new.md", line: "A new command" },
  ]);
});

test("docs/pirate/cli is what pirate-cli.mjs generates (run `aube run pirate:cli` after editing docs/pirate/cli.json)", () => {
  const words = readWords();
  const pages = cliPages();
  for (const page of pages) {
    // Read as the generator reads its input, whatever line endings the checkout uses.
    const onDisk = readFileSync(join(DOCS, "pirate/cli", page), "utf8").replace(/\r\n/g, "\n");
    assert.equal(onDisk, pirateCliPage(page, words).text, page);
  }
  // And no page is left for a command whose English page is gone.
  const pirate = globSync("**/*.md", { cwd: join(DOCS, "pirate/cli") }).map((p) => p.split("\\").join("/"));
  assert.deepEqual(pirate.filter((page) => !pages.includes(page)).sort(), [], "pirate CLI pages with no English page");
});
