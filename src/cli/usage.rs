use crate::Result;
use crate::cli::Cli;
use clap::CommandFactory;

/// Generates a usage spec for the CLI
///
/// https://usage.jdx.dev
#[derive(Debug, clap::Args)]
#[clap(hide = true, verbatim_doc_comment)]
pub struct Usage {}

impl Usage {
    pub async fn run(&self) -> Result<()> {
        let cmd = Cli::command();
        let mut spec: usage::Spec = cmd.into();
        spec.bin = "hk".to_string();
        // Declare what each command does to the world; clap cannot express it.
        super::command_effects::apply(&mut spec);
        // 3.6 added `effect=`; older `usage` CLIs reject the spec outright with
        // "unsupported cmd prop effect".
        let usage = format!(
            "// @generated by usage-cli from clap metadata\nmin_usage_version \"3.6\"\n{spec}\n"
        ) + include_str!("../hk-extras.usage.kdl");
        println!("{}", usage.trim());
        Ok(())
    }
}
